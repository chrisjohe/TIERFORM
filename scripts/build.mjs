import fs from 'node:fs/promises';
import path from 'node:path';
import {VERSION} from '../src/model/settings.js';
import {writeLegacySource} from './legacy-source.mjs';
import {build} from 'esbuild';
const root=path.resolve(import.meta.dirname,'..');
process.chdir(root);
const CSP="default-src 'none'; script-src 'self'; style-src 'self' 'unsafe-inline'; img-src data:; font-src 'self'; connect-src 'none'; form-action 'none'; base-uri 'none'; object-src 'none'";
const result=await build({entryPoints:['src/main.js'],bundle:true,write:false,format:'iife',target:'es2022',legalComments:'none',minify:false,charset:'utf8'});
const js=result.outputFiles[0].text;
const styles=['base','ribbon','info-tour','controls','roster','workspace','dialogs','theme'];
const css=(await Promise.all(styles.map(name=>fs.readFile('src/styles/'+name+'.css','utf8')))).join('');
const fontCSS=await fs.readFile('src/styles/fonts.css','utf8');
const font=await fs.readFile('fonts/OpenSans-VariableFont_wdth,wght.woff2');
let template=await fs.readFile('src/markup/index.html','utf8');
const parts=['sprite.html','ribbon.html','menus.html','workspace.html','dialogs.html','info.html','tour.html'];
const body=(await Promise.all(parts.map(n=>fs.readFile('src/markup/'+n,'utf8')))).join('\n');
template=template.replace('{{BODY}}',body);
const offline=template.replace('{{STYLES}}','<style>\n'+css+'</style>\n<style id="fontcss">\n'+fontCSS.replace('./OpenSans.woff2','data:font/woff2;base64,'+font.toString('base64'))+'</style>').replace('{{SCRIPT}}','<script>\n'+js+'</script>');
const hosted=template.replace('<meta charset="utf-8">','<meta charset="utf-8">\n<meta http-equiv="Content-Security-Policy" content="'+CSP+'">').replace('{{STYLES}}','<link rel="stylesheet" href="./assets/app.css">\n<link rel="stylesheet" href="./assets/fonts.css">').replace('{{SCRIPT}}','<script src="./assets/app.js"></script>');
await fs.rm('_site',{recursive:true,force:true});
await fs.mkdir('_site/assets',{recursive:true});
await Promise.all([fs.writeFile('tierform_app.html',offline),fs.writeFile('_site/index.html',hosted),fs.writeFile('_site/tierform_app.html',offline),fs.writeFile('_site/assets/app.js',js),fs.writeFile('_site/assets/app.css',css),fs.writeFile('_site/assets/fonts.css',fontCSS),fs.writeFile('_site/assets/OpenSans.woff2',font)]);
await writeLegacySource();
console.log(`Built ${VERSION}: tierform_app.html and _site/`);
